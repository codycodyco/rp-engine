    // ---- the same pixels as Studio ------------------------------------------

    /**
     * Every fixture ResourcePack AI Studio drew with its own renderer, drawn
     * here from the same spec, compared pixel by pixel. This is the whole
     * agreement between the two renderers: a failure names the fixture and
     * the first pixel that differs.
     */
    @Test
    void everyFixtureDrawsAsStudioDrewIt() throws IOException {
        JsonObject root;
        try (InputStream in = RankTagsTest.class.getResourceAsStream("/rank-tags/fixtures.json")) {
            assertNotNull(in, "rank-tags/fixtures.json is missing; it is generated by Studio's rank tag renderer");
            root = JsonParser.parseString(new String(in.readAllBytes(), StandardCharsets.UTF_8)).getAsJsonObject();
        }
        JsonArray fixtures = root.getAsJsonArray("fixtures");
        assertTrue(fixtures.size() > 20, "too few fixtures to mean anything");
        List<String> failures = new ArrayList<>();
        for (JsonElement element : fixtures) {
            JsonObject f = element.getAsJsonObject();
            String name = f.get("name").getAsString();
            RankTags.Drawn drawn = RankTags.render(specOf(f.getAsJsonObject("spec")));
            int width = f.get("width").getAsInt();
            int height = f.get("height").getAsInt();
            if (drawn.width() != width || drawn.height() != height) {
                failures.add(name + ": " + drawn.width() + "x" + drawn.height() + " where Studio drew " + width + "x" + height);
                continue;
            }
            if (drawn.ascent() != f.get("ascent").getAsInt()) {
                failures.add(name + ": ascent " + drawn.ascent() + " where Studio has " + f.get("ascent").getAsInt());
            }
            JsonArray palette = f.getAsJsonArray("palette");
            JsonArray rows = f.getAsJsonArray("rows");
            outer:
            for (int y = 0; y < height; y++) {
                String row = rows.get(y).getAsString();
                for (int x = 0; x < width; x++) {
                    String colour = palette.get(digit(row.charAt(x))).getAsString();
                    int expected = colour.equals("transparent") ? 0 : 0xff000000 | Integer.parseInt(colour.substring(1), 16);
                    if (drawn.at(x, y) != expected) {
                        failures.add(name + ": pixel " + x + "," + y + " is " + Integer.toHexString(drawn.at(x, y))
                                + " where Studio drew " + Integer.toHexString(expected));
                        break outer;
                    }
                }
            }
        }
        assertTrue(failures.isEmpty(), String.join("\n", failures));
    }

    private static int digit(char c) {
        String digits = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
        return digits.indexOf(c);
    }

    /** Studio's stored spec (camelCase, hex strings, optional fields absent) as the engine's. */
    private static RankTags.Spec specOf(JsonObject s) {
        return new RankTags.Spec(
                s.get("text").getAsString(),
                s.get("font").getAsString(),
                hex(s, "textColor"),
                optionalHex(s, "textColor2"),
                s.get("bold").getAsBoolean(),
                s.get("shadow").getAsBoolean(),
                optionalHex(s, "shadowColor"),
                s.get("spacing").getAsInt(),
                hex(s, "fill"),
                optionalHex(s, "fill2"),
                s.get("style").getAsString(),
                s.get("border").getAsInt(),
                optionalHex(s, "borderColor"),
                s.get("radius").getAsInt(),
                s.get("padX").getAsInt(),
                s.get("padY").getAsInt(),
                s.has("width") ? s.get("width").getAsInt() : null,
                s.get("scale").getAsInt(),
                s.get("offset").getAsInt());
    }

    private static int hex(JsonObject s, String key) {
        return Integer.parseInt(s.get(key).getAsString().substring(1), 16);
    }

    private static Integer optionalHex(JsonObject s, String key) {
        return s.has(key) ? hex(s, key) : null;
    }

    // ---- reading -----------------------------------------------------------

    @Test
    void theClassicTagIsOneChatLineTall() {
        RankTags.Drawn drawn = RankTags.render(RankTags.Spec.defaults("OWNER"));
        assertEquals(9, drawn.height(), "outline + padding + five-row capitals + padding + outline");
        assertEquals(8, drawn.ascent(), "fills the chat line's nine rows exactly");
    }

    @Test
    void codesColourPartOfTheWords() {
        List<RankTags.Run> runs = RankTags.runs("VIP&6+&rX&zY", false);
        assertEquals(3, runs.size());
        assertEquals("VIP", runs.get(0).text());
        assertEquals(0xffaa00, runs.get(1).color());
        assertEquals("X&zY", runs.get(2).text(), "&r resets, and &z is not a code so it stays");
        assertEquals("VIP+X&zY", RankTags.plain("VIP&6+&rX&zY"));
    }

    @Test
    void coloursAreHexOrTheGamesNames() {
        assertEquals(0xe53935, RankTags.colour("#e53935").orElseThrow());
        assertEquals(0xe53935, RankTags.colour("E53935").orElseThrow());
        assertEquals(0xffaa00, RankTags.colour("gold").orElseThrow());
        assertEquals(0xaa0000, RankTags.colour("dark red").orElseThrow());
        assertEquals(0xff0000, RankTags.colour("#f00").orElseThrow());
        assertTrue(RankTags.colour("reddish").isEmpty());
    }

    // ---- in a content folder ------------------------------------------------

    @TempDir
    Path root;

    private Path content;
    private Path out;

    @BeforeEach
    void setUp() throws IOException {
        content = root.resolve("content");
        out = root.resolve("out");
        Files.createDirectories(content);
        write("mypack/pack.yml", "{}\n");
    }

    private void write(String path, String text) throws IOException {
        Path file = content.resolve(path);
        Files.createDirectories(file.getParent());
        Files.writeString(file, text, StandardCharsets.UTF_8);
    }

    private LoadReport load() {
        return new ContentFolderLoader(new ContentRegistryImpl()).load(content, ContentSource.AUTHORED);
    }

    private Map<String, byte[]> zip() throws IOException {
        BuildReport report = new PackBuilder().with(new FontAssets()).build(content, out, load());
        Map<String, byte[]> entries = new LinkedHashMap<>();
        try (InputStream in = Files.newInputStream(report.pack("main").orElseThrow().file());
             ZipInputStream zin = new ZipInputStream(in)) {
            ZipEntry entry;
            while ((entry = zin.getNextEntry()) != null) {
                entries.put(entry.getName(), zin.readAllBytes());
            }
        }
        return entries;
    }

    @Test
    void aTagIsAnIconTheBuildDraws() throws IOException {
        write("mypack/fonts/ranks.yml", """
                owner:
                  tag:
                    text: OWNER
                    background: "#e53935"
                admin:
                  tag:
                    text: ADMIN
                    background: dark_red
                    roundness: pill
                    outline: 2
                """);
        IconDefinitions.Result result = IconDefinitions.parse(load());
        assertTrue(result.diagnostics().isEmpty(), result.diagnostics().toString());
        IconInfo owner = result.icons().get(ContentId.parse("mypack:owner").orElseThrow());
        assertNotNull(owner);
        assertEquals(9, owner.height());
        assertEquals(8, owner.ascent());
        assertEquals("rank_tags/owner", owner.file());
        assertTrue(result.tags().containsKey(owner.id()));

        Map<String, byte[]> zip = zip();
        byte[] png = zip.get("assets/mypack/textures/font/rank_tags/owner.png");
        assertNotNull(png, "the build writes the drawing where the provider points");
        BufferedImage image = ImageIO.read(new ByteArrayInputStream(png));
        RankTags.Drawn drawn = RankTags.render(RankTags.Spec.defaults("OWNER"));
        assertEquals(drawn.width(), image.getWidth());
        assertEquals(drawn.height(), image.getHeight());
        assertEquals(drawn.at(5, 4), image.getRGB(5, 4));
        String font = new String(zip.get(FontAssets.DEFAULT_FONT), StandardCharsets.UTF_8);
        assertTrue(font.contains("\"file\": \"mypack:font/rank_tags/owner.png\""), font);
        assertTrue(font.contains("\"height\": 9"), font);
    }

    @Test
    void mistakesAreWarningsAndTheTagStillDraws() {
        List<Diagnostic> diagnostics = new ArrayList<>();
        var node = ai.resourcepack.engine.api.DefinitionNode.of(Map.of(
                "text", "VIP", "background", "reddish", "font", "comic", "outline", 9, "shading", "shiny"));
        RankTags.Spec spec = RankTags.parse(node, "mypack/fonts", "vip", diagnostics).orElseThrow();
        assertEquals(4, diagnostics.size(), diagnostics.toString());
        assertEquals("classic", spec.font());
        assertEquals(2, spec.border());
        assertEquals("glossy", spec.style());
        assertEquals(0xe53935, spec.fill());
    }

    @Test
    void aTagWithNoWordsIsRefused() throws IOException {
        write("mypack/fonts/ranks.yml", """
                blank:
                  tag:
                    background: red
                """);
        IconDefinitions.Result result = IconDefinitions.parse(load());
        assertFalse(result.icons().containsKey(ContentId.parse("mypack:blank").orElseThrow()));
        assertTrue(result.diagnostics().stream().anyMatch(d -> d.message().contains("needs text")));
    }

    @Test
    void aFileOnATagIsIgnoredWithAWarning() throws IOException {
        write("mypack/fonts/ranks.yml", """
                mod:
                  file: mod
                  height: 16
                  tag:
                    text: MOD
                """);
        IconDefinitions.Result result = IconDefinitions.parse(load());
        IconInfo mod = result.icons().get(ContentId.parse("mypack:mod").orElseThrow());
        assertEquals(9, mod.height());
        assertEquals(2, result.diagnostics().size(), result.diagnostics().toString());
    }

    @Test
    void thePlayerWearsTheHighestPriorityTagTheyHold() throws IOException {
        write("mypack/fonts/ranks.yml", """
                owner:
                  priority: 100
                  tag:
                    text: OWNER
                vip:
                  priority: 10
                  tag:
                    text: VIP
                staff/mod:
                  priority: 50
                  tag:
                    text: MOD
                coin:
                  file: coin
                """);
        IconDefinitions.Result result = IconDefinitions.parse(load());
        RankTagWearers wearers = new RankTagWearers();
        wearers.replace(result);

        ContentId owner = ContentId.parse("mypack:owner").orElseThrow();
        ContentId vip = ContentId.parse("mypack:vip").orElseThrow();
        ContentId mod = ContentId.parse("mypack:staff/mod").orElseThrow();
        assertEquals("rpengine.tag.mypack.owner", RankTagWearers.permission(owner));
        assertEquals("rpengine.tag.mypack.staff.mod", RankTagWearers.permission(mod));
        assertEquals(3, wearers.permissions().size(), "one node per tag, none for a plain icon");

        java.util.Set<String> held = new java.util.HashSet<>(List.of("rpengine.tag.mypack.vip", "rpengine.tag.mypack.staff.mod"));
        assertEquals(java.util.Optional.of(mod), wearers.tagOf(held::contains), "MOD outranks VIP");
        held.add("rpengine.tag.mypack.owner");
        assertEquals(java.util.Optional.of(owner), wearers.tagOf(held::contains));
        assertEquals(java.util.Optional.of(vip), wearers.tagOf("rpengine.tag.mypack.vip"::equals));
        assertTrue(wearers.tagOf(node -> false).isEmpty(), "holding none is wearing none");
    }

    @Test
    void anAscentWinsOverTheCentredOne() throws IOException {
        write("mypack/fonts/ranks.yml", """
                vip:
                  ascent: 7
                  tag:
                    text: VIP
                    scale: 2
                """);
        IconInfo vip = IconDefinitions.parse(load()).icons().get(ContentId.parse("mypack:vip").orElseThrow());
        assertEquals(18, vip.height());
        assertEquals(7, vip.ascent());
    }
